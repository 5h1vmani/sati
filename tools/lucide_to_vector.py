"""Download Lucide icons and convert them to Android VectorDrawable XML.

Lucide icons are 24x24 line drawings with stroke width 2 and round caps.
Each SVG element becomes one <path> with the same stroke settings.

Usage: python3 tools/lucide_to_vector.py
Writes app/src/main/res/drawable/lucide_<name>.xml for every name in ICONS.
"""
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

VERSION = "1.64.0"
ICONS = [
    "bell", "bell-off", "pause", "play", "square", "shuffle",
    "sunrise", "music", "volume-2", "volume-x", "triangle-alert",
    "battery", "alarm-clock", "snowflake", "vibrate", "moon",
]
OUT = Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"
NS = "{http://www.w3.org/2000/svg}"


def num(v):
    return float(v)


def to_path(el):
    tag = el.tag.replace(NS, "")
    a = el.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = num(a["cx"]), num(a["cy"]), num(a["r"])
        return f"M{cx - r},{cy}a{r},{r} 0 1,0 {2 * r},0a{r},{r} 0 1,0 {-2 * r},0"
    if tag == "ellipse":
        cx, cy, rx, ry = num(a["cx"]), num(a["cy"]), num(a["rx"]), num(a["ry"])
        return f"M{cx - rx},{cy}a{rx},{ry} 0 1,0 {2 * rx},0a{rx},{ry} 0 1,0 {-2 * rx},0"
    if tag == "line":
        return f"M{a['x1']},{a['y1']}L{a['x2']},{a['y2']}"
    if tag in ("polyline", "polygon"):
        pts = re.split(r"[\s,]+", a["points"].strip())
        pairs = [f"{pts[i]},{pts[i + 1]}" for i in range(0, len(pts), 2)]
        d = "M" + "L".join(pairs)
        return d + ("Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y = num(a.get("x", 0)), num(a.get("y", 0))
        w, h = num(a["width"]), num(a["height"])
        rx = num(a.get("rx", a.get("ry", 0)))
        if rx == 0:
            return f"M{x},{y}h{w}v{h}h{-w}Z"
        return (f"M{x + rx},{y}h{w - 2 * rx}a{rx},{rx} 0 0 1 {rx},{rx}v{h - 2 * rx}"
                f"a{rx},{rx} 0 0 1 {-rx},{rx}h{-(w - 2 * rx)}a{rx},{rx} 0 0 1 {-rx},{-rx}"
                f"v{-(h - 2 * rx)}a{rx},{rx} 0 0 1 {rx},{-rx}Z")
    raise ValueError(f"unsupported element {tag}")


def convert(name, svg):
    root = ET.fromstring(svg)
    paths = [to_path(el) for el in root.iter() if el is not root]
    body = "\n".join(
        f'    <path\n        android:pathData="{d}"\n'
        f'        android:strokeColor="#FFFFFFFF"\n'
        f'        android:strokeWidth="2"\n'
        f'        android:strokeLineCap="round"\n'
        f'        android:strokeLineJoin="round" />'
        for d in paths
    )
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Lucide "{name}" v{VERSION}, ISC license. Generated by tools/lucide_to_vector.py. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="24dp"\n    android:height="24dp"\n'
            f'    android:viewportWidth="24"\n    android:viewportHeight="24">\n'
            f'{body}\n</vector>\n')


def main():
    for name in ICONS:
        url = f"https://unpkg.com/lucide-static@{VERSION}/icons/{name}.svg"
        svg = urllib.request.urlopen(url, timeout=20).read().decode()
        out = OUT / f"lucide_{name.replace('-', '_')}.xml"
        out.write_text(convert(name, svg))
        print("wrote", out.name)


if __name__ == "__main__":
    sys.exit(main())
